#!/usr/bin/env python3
"""Generate C++ IQ tables from a table source file.

Usage: python3 tools/gen_tables.py <tables.rs> include/tokshit/gguf_tables.hpp
"""

import re
import sys


def parse_tables(text):
    tables = {}
    pattern = re.compile(
        r"pub const (\w+):\s*\[(\w+);\s*(\d+)\]\s*=\s*\[(.*?)\];",
        re.S,
    )
    for match in pattern.finditer(text):
        name, ty, count, body = match.groups()
        values = re.findall(r"-?\b(?:0x[0-9a-fA-F]+|\d+)\b", body)
        assert len(values) == int(count), (name, len(values), count)
        tables[name] = (ty, values)
    return tables


CPP_TYPE = {
    "u8": "std::uint8_t",
    "u32": "std::uint32_t",
    "u64": "std::uint64_t",
    "i8": "std::int8_t",
}


def render(tables):
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/gen_tables.py. Do not edit by hand.",
        "",
        "#include <array>",
        "#include <cstdint>",
        "",
        "namespace tokshit::tables {",
        "",
    ]
    for name, (ty, values) in tables.items():
        cpp_ty = CPP_TYPE[ty]
        lines.append(f"inline constexpr std::array<{cpp_ty}, {len(values)}> {name.lower()} = {{")
        for i in range(0, len(values), 8):
            chunk = values[i : i + 8]
            if ty == "i8":
                rendered = ", ".join(chunk)
            else:
                rendered = ", ".join(chunk)
            lines.append("    " + rendered + ",")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace tokshit::tables")
    lines.append("")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding="utf-8") as src:
        tables = parse_tables(src.read())
    with open(sys.argv[2], "w", encoding="utf-8") as dst:
        dst.write(render(tables))
    print(f"generated {len(tables)} tables -> {sys.argv[2]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
